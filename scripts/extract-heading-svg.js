// scripts/extract-heading-svg.js
const fs = require('fs')
const path = require('path')
const opentype = require('opentype.js')

const FONT_PATH = path.join(__dirname, 'Syne-ExtraBold.ttf')
const OUTPUT_TS = path.join(__dirname, '..', 'src', 'components', 'motion', 'portalHeadingPaths.ts')

function run() {
  const buffer = fs.readFileSync(FONT_PATH)
  const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength))

  const fontSize = 1000 // Unit font size for vector normalization

  function getWordLayout(word, letterSpacing = 0) {
    let currentX = 0
    const glyphs = []
    
    for (let i = 0; i < word.length; i++) {
      const char = word[i]
      const glyph = font.charToGlyph(char)
      const kerning = i < word.length - 1 ? font.getKerningValue(glyph, font.charToGlyph(word[i + 1])) : 0
      const glyphPath = glyph.getPath(currentX, 0, fontSize)
      
      glyphs.push({
        char,
        x: currentX,
        advanceWidth: glyph.advanceWidth,
        d: glyphPath.toPathData(2),
        bbox: glyph.getBoundingBox(),
      })
      
      currentX += glyph.advanceWidth + kerning + letterSpacing
    }
    
    return {
      word,
      totalWidth: currentX,
      glyphs,
    }
  }

  const line1 = getWordLayout('Event', -20)
  const line2 = getWordLayout('Gpt', -20)

  // Find p glyph details in line 2
  const pGlyph = line2.glyphs.find(g => g.char === 'p')
  
  // Also get the single combined path for line 1 and line 2
  const line1Path = font.getPath('Event', 0, 0, fontSize, { kerning: true, letterSpacing: -0.02 })
  const line2Path = font.getPath('Gpt', 0, 0, fontSize, { kerning: true, letterSpacing: -0.02 })

  // Specifically for 'p': extract counter contour to find exact counter center
  const rawPGlyph = font.charToGlyph('p')
  const pPath = rawPGlyph.getPath(0, 0, fontSize)
  
  // Split p commands by M to find counter
  const contours = []
  let curr = []
  for (const cmd of pPath.commands) {
    if (cmd.type === 'M' && curr.length > 0) {
      contours.push(curr)
      curr = []
    }
    curr.push(cmd)
  }
  if (curr.length > 0) contours.push(curr)

  // Contour 1 in Syne ExtraBold is the counter
  const counterContour = contours[1] || []
  let minCX = Infinity, maxCX = -Infinity, minCY = Infinity, maxCY = -Infinity
  for (const cmd of counterContour) {
    if (cmd.x !== undefined) {
      minCX = Math.min(minCX, cmd.x)
      maxCX = Math.max(maxCX, cmd.x)
    }
    if (cmd.y !== undefined) {
      minCY = Math.min(minCY, cmd.y)
      maxCY = Math.max(maxCY, cmd.y)
    }
  }

  const counterCenterXInP = (minCX + maxCX) / 2
  const counterCenterYInP = (minCY + maxCY) / 2

  const outputCode = `// Generated by scripts/extract-heading-svg.js
// Syne ExtraBold glyph vector paths for "Event" / "Gpt"

export interface GlyphData {
  char: string
  x: number
  advanceWidth: number
  d: string
}

export const HEADING_SVG_DATA = {
  unitsPerEm: ${font.unitsPerEm},
  ascender: ${font.ascender},
  descender: ${font.descender},
  fontSize: ${fontSize},
  line1: {
    text: 'Event',
    totalWidth: ${line1.totalWidth},
    pathD: '${line1Path.toPathData(2)}',
    glyphs: ${JSON.stringify(line1.glyphs.map(g => ({ char: g.char, x: g.x, advanceWidth: g.advanceWidth, d: g.d })), null, 2)},
  },
  line2: {
    text: 'Gpt',
    totalWidth: ${line2.totalWidth},
    pathD: '${line2Path.toPathData(2)}',
    glyphs: ${JSON.stringify(line2.glyphs.map(g => ({ char: g.char, x: g.x, advanceWidth: g.advanceWidth, d: g.d })), null, 2)},
    pOffset: {
      x: ${pGlyph.x},
      counterCenterX: ${pGlyph.x + counterCenterXInP},
      counterCenterY: ${counterCenterYInP},
      counterWidth: ${maxCX - minCX},
      counterHeight: ${maxCY - minCY},
    },
  },
} as const
`

  fs.writeFileSync(OUTPUT_TS, outputCode)
  console.log('Successfully wrote', OUTPUT_TS)
}

run()

