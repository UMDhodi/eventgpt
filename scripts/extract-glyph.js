// scripts/extract-glyph.js
const fs = require('fs')
const path = require('path')
const https = require('https')
const opentype = require('opentype.js')

const FONT_URL = 'https://fonts.gstatic.com/s/syne/v24/8vIS7w4qzmVxsWxjBZRjr0FKM_24vj6kR4jNCA.ttf'
const FONT_LOCAL = path.join(__dirname, 'Syne-ExtraBold.ttf')
const OUTPUT_TS = path.join(__dirname, '..', 'src', 'components', 'motion', 'pGlyphPaths.ts')

function downloadFont() {
  return new Promise((resolve, reject) => {
    if (fs.existsSync(FONT_LOCAL)) {
      return resolve(fs.readFileSync(FONT_LOCAL))
    }
    console.log('Downloading Syne-ExtraBold.ttf...')
    https.get(FONT_URL, (res) => {
      const data = []
      res.on('data', (chunk) => data.push(chunk))
      res.on('end', () => {
        const buffer = Buffer.concat(data)
        fs.writeFileSync(FONT_LOCAL, buffer)
        resolve(buffer)
      })
      res.on('error', reject)
    })
  })
}

async function run() {
  const buffer = await downloadFont()
  const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength))
  const glyph = font.charToGlyph('p')
  const pathData = glyph.getPath(0, 0, 1000)

  // Shift commands by (-45, 504) to normalize minX to 0 and minY to 0
  const offsetX = 45
  const offsetY = -504 // subtracting -504 is adding 504

  for (const cmd of pathData.commands) {
    if (cmd.x !== undefined) cmd.x -= offsetX
    if (cmd.y !== undefined) cmd.y -= offsetY
    if (cmd.x1 !== undefined) cmd.x1 -= offsetX
    if (cmd.y1 !== undefined) cmd.y1 -= offsetY
    if (cmd.x2 !== undefined) cmd.x2 -= offsetX
    if (cmd.y2 !== undefined) cmd.y2 -= offsetY
  }

  // Split into contours by 'M'
  const contours = []
  let current = []
  for (const cmd of pathData.commands) {
    if (cmd.type === 'M' && current.length > 0) {
      contours.push(current)
      current = []
    }
    current.push(cmd)
  }
  if (current.length > 0) contours.push(current)

  // In Syne ExtraBold 'p':
  // Contour 0: outer bowl
  // Contour 1: counter (inner hole)
  // Contour 2: stem & descender
  const outerContour = [...contours[0], ...contours[2]]
  const counterContour = contours[1]

  const pOuterPath = new opentype.Path()
  pOuterPath.commands = outerContour

  const pCounterPath = new opentype.Path()
  pCounterPath.commands = counterContour

  const pFullPath = new opentype.Path()
  pFullPath.commands = pathData.commands

  const outerD = pOuterPath.toPathData(2)
  const counterD = pCounterPath.toPathData(2)
  const fullD = pFullPath.toPathData(2)

  // Calculate normalized 0-1 counter path for clip-path: polygon / SVG mask
  const glyphW = 983
  const glyphH = 704
  const counterBBox = {
    minX: 240,
    minY: 152,
    maxX: 734,
    maxY: 366,
    width: 494,
    height: 214,
    centerX: 487,
    centerY: 259,
  }

  const outputCode = `// Generated by scripts/extract-glyph.js using opentype.js from Syne ExtraBold
// Normalised glyph metrics for letter "p"
export const P_GLYPH_METRICS = {
  width: ${glyphW},
  height: ${glyphH},
  advanceWidth: ${glyph.advanceWidth},
  viewBox: '0 0 ${glyphW} ${glyphH}',
  counter: {
    minX: ${counterBBox.minX},
    minY: ${counterBBox.minY},
    maxX: ${counterBBox.maxX},
    maxY: ${counterBBox.maxY},
    width: ${counterBBox.width},
    height: ${counterBBox.height},
    centerX: ${counterBBox.centerX},
    centerY: ${counterBBox.centerY},
    centerPercentX: ${(counterBBox.centerX / glyphW * 100).toFixed(2)},
    centerPercentY: ${(counterBBox.centerY / glyphH * 100).toFixed(2)},
  },
} as const

// Outer boundary of "p" (stem + descender + outer bowl)
export const P_OUTER_PATH = '${outerD}'

// Inner contour of "p" (the counter hole)
export const P_COUNTER_PATH = '${counterD}'

// Combined glyph path with both outer and counter for fillRule="evenodd"
export const P_FULL_GLYPH_PATH = '${fullD}'
`

  fs.writeFileSync(OUTPUT_TS, outputCode)
  console.log('Successfully wrote', OUTPUT_TS)
}

run().catch(console.error)

